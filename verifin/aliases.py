"""财务口语简称 → 报表规范科目名（见留档 P-030）。

为什么需要这个模块
------------------
现金流量表里大量行名都含「现金流」三个字：三张活动表各有「流入小计 / 流出小计 /
产生的现金流量净额」共 9 行。口语简称「经营现金流」在词面上同时沾到其中若干行，
BM25 与 TF-IDF 都无法判断用户指的是哪一行，于是 RRF **不一定**取到「净额」那一行。

实测（茅台 2024 年报）::

    「经营现金流是多少」          → 向中央银行借款净增加额（错误行）
    「经营活动现金流净额是多少」  → 赔付支出净额（错误行）

返回的都是**真实数字、真实页码**。非财务专家根本分不出对错 —— 典型的
"看起来对、实际错"的静默错误，比直接拒答更危险，因为它悄悄破坏了信任。

本模块把这件事从"靠检索排序碰运气"变成"确定性的意图归一"：
问句进检索之前先做简称展开，让「经营现金流」直接变成
「经营活动产生的现金流量净额」，指名道姓地取那一行。

设计约定（四条，都由实测教训得来）
--------------------------------
1. **只收确定性映射，不收有歧义的词**。
   「营收」在报表里对应「营业收入」与「营业总收入」两行且数值不同
   （2024：170,899,152,276.34 vs 174,144,069,958.25）。凭语感二选一，
   等于用猜测换掉一次拒答 —— 这个项目里给错一个财务数字的代价远高于拒答。
   有歧义的简称单独登记在 :data:`AMBIGUOUS_ABBREVIATIONS`，供上层给出
   **明确的歧义拒答原因**，而不是让它退化成笼统的"没召回"。

2. **不做前缀/后缀模糊匹配**。理由同 :data:`verifin.agent.tools.LABEL_ALIAS`：
   模糊匹配会让「负债合计」落到「非流动负债合计」上，那正是要防的张冠李戴。

3. **替换一律最长优先**，否则「经营活动现金流」会被「经营现金流」先咬掉一半，
   留下「活动」这种无意义残渣污染后续检索。

4. **展开与歧义检测必须在同一次扫描里完成**（这条是实测打出来的，见下）。

为什么展开与检测必须合并成一趟
------------------------------
第一版把两者拆成两个函数、依次调用（先 `expand_question` 再 `detect_ambiguous`），
实测立刻出错::

    「2024年经营现金流是多少」
      expand  → 「2024年经营活动产生的现金流量净额是多少」
      detect  → 命中「现金流」→ 误报歧义

展开后的**规范名本身就含「现金流」三个字**，于是第二步把刚刚展开干净的问句
又判成了有歧义 —— 假阳性，会把本来能答对的问题拦掉。

根因是"两次扫描"这个结构本身：第二次扫描无法区分
「用户本来写的简称」与「上一步替换进去的规范名」。
改成 :func:`normalize_question` 的单趟扫描后，`re.sub` 的替换结果
不参与后续匹配，这个问题在结构上就不存在了。

与 :data:`verifin.agent.tools.LABEL_ALIAS` 的分工
------------------------------------------------
`LABEL_ALIAS` 解决的是「**公式规范名** ≠ 报表披露名」（P-012），
输入已经是规范科目名，只需换个写法；本模块解决的是「**用户口语** → 规范科目名」，
输入是自然语言问句，需要先从句子里把简称找出来。两者层级不同，故分开放。
"""

from __future__ import annotations

import re
from dataclasses import dataclass

__all__ = [
    "ABBREVIATION_ALIASES",
    "AMBIGUOUS_ABBREVIATIONS",
    "QuestionNorm",
    "expand_question",
    "detect_ambiguous",
    "normalize_question",
]


#: 口语简称 → 报表规范科目名。**每一对都经过实测确认目标行真实存在**，
#: 且该简称在报表语境下只可能指这一行。
#:
#: 收录判据（三条全满足才收）：
#: 1. 该简称在词法上会与同族多行混淆（否则检索本来就能取对，收了是冗余）；
#: 2. 展开后的规范名在报表里**确实存在**（否则是死映射，展开后照样拒答）；
#: 3. 该简称在财务语境下**语义唯一**（有歧义的一律进 AMBIGUOUS_ABBREVIATIONS）。
ABBREVIATION_ALIASES: dict[str, str] = {
    # 现金流量表三张活动表：口语说「X 现金流」时，指的必然是「X 活动产生的现金流量净额」。
    # 「净额」是这三个简称的隐含语义 —— 这正是词法检索抓不住的地方。
    "经营现金流": "经营活动产生的现金流量净额",
    "经营活动现金流": "经营活动产生的现金流量净额",
    # 「现金流量净额」是口语里最顺的一种说法，却**不是**「现金流净额」——
    # 中间多一个「量」。不单独登记的话，长别名「经营现金流」会先咬掉前半截，
    # 剩下「量净额」拼进规范名，产出「……现金流量净额量净额」这个不存在的科目名。
    # 实测：问「2024年经营现金流量净额是多少」得到的就是这个拼坏的名字。
    # 这一族只能靠**最长优先 + 显式登记**解决，词尾保护只能兜住没登记到的变体。
    "经营现金流量净额": "经营活动产生的现金流量净额",
    "经营活动现金流量净额": "经营活动产生的现金流量净额",
    "经营现金流净额": "经营活动产生的现金流量净额",
    "经营活动现金流净额": "经营活动产生的现金流量净额",
    "投资现金流": "投资活动产生的现金流量净额",
    "投资活动现金流": "投资活动产生的现金流量净额",
    "投资现金流量净额": "投资活动产生的现金流量净额",
    "投资活动现金流量净额": "投资活动产生的现金流量净额",
    "投资现金流净额": "投资活动产生的现金流量净额",
    "投资活动现金流净额": "投资活动产生的现金流量净额",
    "筹资现金流": "筹资活动产生的现金流量净额",
    "筹资活动现金流": "筹资活动产生的现金流量净额",
    "筹资现金流量净额": "筹资活动产生的现金流量净额",
    "筹资活动现金流量净额": "筹资活动产生的现金流量净额",
    "筹资现金流净额": "筹资活动产生的现金流量净额",
    "筹资活动现金流净额": "筹资活动产生的现金流量净额",
    # 归母类简称：「归母」是「归属于母公司」的行业通用缩写，语义唯一。
    "归母净利润": "归属于母公司股东的净利润",
    "归母净利": "归属于母公司股东的净利润",
    "归母权益": "归属于母公司所有者权益（或股东权益）合计",
    "归母股东权益": "归属于母公司所有者权益（或股东权益）合计",
}


#: 有歧义的口语简称 → 它在报表里可能对应的多行。**刻意不映射**，
#: 而是让上层给出明确的歧义拒答原因。
#:
#: 为什么不做"选一个最像的"：两个候选都是真实科目、数值不同，
#: 猜错就是答非所问，而答非所问通过全部数值/页码/span 护栏 —— 用户无从分辨。
#: 显式拒答并说明"可能指 A 或 B"，是把选择权还给用户，代价只是多问一句。
AMBIGUOUS_ABBREVIATIONS: dict[str, tuple[str, ...]] = {
    "营收": ("营业收入", "营业总收入"),
    "净资产": (
        "所有者权益（或股东权益）合计",
        "归属于母公司所有者权益（或股东权益）合计",
    ),
    "现金流": (
        "经营活动产生的现金流量净额",
        "投资活动产生的现金流量净额",
        "筹资活动产生的现金流量净额",
    ),
}


#: 一张简称不允许**同时**出现在两个表里：那意味着它既被当作确定映射、
#: 又被当作有歧义 —— 两种解释互相矛盾，且行为取决于遍历顺序，不可复现。
#: 这类冲突在模块加载期就炸掉，不留给运行时的隐式顺序背锅。
_CONFLICT: frozenset[str] = frozenset(ABBREVIATION_ALIASES) & frozenset(
    AMBIGUOUS_ABBREVIATIONS
)
if _CONFLICT:
    raise ValueError(
        f"简称同时登记为确定映射与歧义映射，语义矛盾：{sorted(_CONFLICT)}"
    )


def _canonical_names() -> frozenset[str]:
    """本模块涉及的全部**规范科目名**：别名表的目标值 + 歧义词的候选值。

    把它们也放进匹配分支，是为了解决一个由「规范名自身含歧义词」引起的假阳性：
    「经营活动产生的现金流量净额」里含「现金流」三字，若不把规范全名
    作为更长的分支参与匹配，用户**直接写全名**提问时会被判成有歧义 ——
    实测确实发生了，且表现为"把本来能答对的问题拦掉"。
    让规范名参与同一趟最长匹配后，全名（14 字）在同位置必然胜过「现金流」（3 字），
    假阳性在结构上消失。
    """
    names = set(ABBREVIATION_ALIASES.values())
    for candidates in AMBIGUOUS_ABBREVIATIONS.values():
        names.update(candidates)
    return frozenset(names)


_CANONICAL = _canonical_names()


#: 别名之后**不允许**紧跟的片段。命中即说明该别名其实是某个更长词/科目名的前缀，
#: 不该被替换、也不该被判成歧义。
#:
#: 为什么必须有这道断言（实测教训，两次回归都是它挡下来的）：
#:
#: 1. **产出不存在的科目名**。第一版只挡了「流入/流出小计」，于是
#:    「投资活动现金流」在问句「投资活动现金流入小计是多少」里被匹配——它恰好是
#:    更长科目名的前缀，替换后产出「投资活动产生的现金流量净额入小计」这个
#:    根本不存在的科目名。检索必然落空，而用户写的是**完全正确的科目全名**，
#:    比原缺陷更糟。一条既有用例当场红掉才暴露出来。
#: 2. **把高频报表名判成歧义简称**（这条更隐蔽，因为它不报错、只是拒答）。
#:    「现金流」这个歧义键会咬到「**现金流量表**」这个到处都在出现的报表名：
#:    问「2024年合并现金流量表的货币资金是多少」会被判成"用了有歧义的简称"
#:    并给出 `AMBIGUOUS_ABBREVIATION` 拒答 —— 一个完全正常的问句被拦掉，
#:    而用户根本没写任何简称。加 `量表` 到断言后，报表名不再被误认。
#:
#: 断言只列**确定的**碰撞后缀，不做宽泛的"后面不能是汉字"
#: （那会把「经营现金流是多少」里的「是」也误伤）。
#: 用显式清单而不是模糊规则，与本模块「只收确定性映射」的约定一致。
_TAIL_GUARD = r"(?![入出]小计|量表)"


def _build_pattern() -> re.Pattern[str] | None:
    """把三张词表编译成「最长优先 + 词尾保护」的单遍匹配正则。

    分支 = 确定别名键 + 歧义简称键 + 规范科目名。

    按长度降序排列分支，是让它天然最长优先的关键：
    Python 正则的交替在同一位置**左侧分支优先**，
    而长度降序恰好把最长的候选排在最左 —— 于是「经营活动现金流」
    不会被「经营现金流」抢先匹配成半个词，规范全名也不会被它的组成部分抢先。

    长度相同时按字典序兜底，保证编译结果与执行结果都可复现。

    Note:
        :data:`_TAIL_GUARD` 是**必须**的，不是锦上添花：没有它，
        别名会作为更长科目名的前缀被误替换并产出不存在的科目名（已实测回归）。
    """
    keys = set(ABBREVIATION_ALIASES) | set(AMBIGUOUS_ABBREVIATIONS) | set(_CANONICAL)
    if not keys:
        return None
    ordered = sorted(keys, key=lambda k: (-len(k), k))
    body = "|".join(re.escape(k) for k in ordered)
    return re.compile(f"(?:{body}){_TAIL_GUARD}")


_PATTERN = _build_pattern()


@dataclass(frozen=True)
class QuestionNorm:
    """一次归一化的完整结果。

    Attributes:
        original: 用户原问句。
        expanded: 简称展开后的问句。上层用它去检索。
        ambiguous: 命中的有歧义简称，每项为 `(简称, 可能对应的科目元组)`。
            保留「可能对应哪些」是为了让拒答说明能**指出具体候选**，
            而不是只丢一句"有歧义"。
    """

    original: str
    expanded: str
    ambiguous: tuple[tuple[str, tuple[str, ...]], ...] = ()

    @property
    def has_ambiguous(self) -> bool:
        return bool(self.ambiguous)


def normalize_question(question: str) -> QuestionNorm:
    """单趟扫描：既展开确定简称，又收集歧义简称。

    **为什么必须一趟**：展开后的规范名本身就含歧义词的字面
    （「经营活动产生的现金流量净额」含「现金流」），
    分两趟做会让第二趟把刚展开干净的结果再次判成有歧义。
    单遍 `re.sub` 的替换结果不参与后续匹配，这个问题在结构上被消掉。

    只做**字典替换**，不改动问句的其余部分 —— 期间、口径、主体等限定词
    原样保留，后续的期间约束与口径消歧照常生效。

    Args:
        question: 用户原问句。

    Returns:
        :class:`QuestionNorm`。没有命中任何简称时 `expanded` 等于 `original`。
    """
    text = question or ""
    if not text or _PATTERN is None:
        return QuestionNorm(text, text)

    ambiguous: list[tuple[str, tuple[str, ...]]] = []
    seen: set[str] = set()

    def replace(match: re.Match[str]) -> str:
        key = match.group(0)
        target = ABBREVIATION_ALIASES.get(key)
        if target is not None:
            return target
        # 规范科目名原样保留 —— 用户已经写对了，没有可归一的东西。
        if key in _CANONICAL:
            return key
        # 歧义简称：**原样保留**，不替换。替换成候选之一就等于替用户做了猜测。
        if key not in seen:
            seen.add(key)
            ambiguous.append((key, AMBIGUOUS_ABBREVIATIONS[key]))
        return key

    expanded = _PATTERN.sub(replace, text)
    return QuestionNorm(text, expanded, tuple(ambiguous))


def expand_question(question: str) -> str:
    """便捷接口：只要展开后的问句。"""
    return normalize_question(question).expanded


def detect_ambiguous(question: str) -> tuple[str, tuple[str, ...]] | None:
    """便捷接口：只要**最长**的那个歧义简称。

    命中多个时取最长者，与 :func:`normalize_question` 的最长优先规则一致
    —— 同一位置只可能有一个最长匹配，取最长才能与替换行为保持同一口径。
    """
    norm = normalize_question(question)
    if not norm.ambiguous:
        return None
    return max(norm.ambiguous, key=lambda item: (len(item[0]), item[0]))