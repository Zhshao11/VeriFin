_applied = False


def apply_lexicon() -> None:
    """把金融词表注入 jieba。幂等，重复调用无副作用。"""
    global _applied
    if _applied:
        return
    import jieba

    for term in (*FINANCIAL_TERMS, *FINANCIAL_PHRASES):
        # freq 调高以确保这些词在最大概率路径一定被切出来
        jieba.add_word(term, freq=100000, tag="nz")
    _applied = True


#: 序号前缀，如 `一、营业总收入` / `（1）货币资金`。
_SECTION_PREFIX = re.compile(r"^[\(（]?[一二三四五六七八九十\d]{1,3}[\)）、.．]\s*")

#: 归属标记前缀，如 `其中:营业收入` / `加:营业外收入` / `减:营业外支出`。
_QUALIFIER_PREFIX = re.compile(r"^(?:其中|加|减|＋|＋:|加：|减：|其中：)[:：]?\s*")

#: 披露脚注后缀，如 `净利润（净亏损以"-"号填列）`。
#: 这些是**填列说明**不是指标名的一部分，留着会让精确匹配失配。
#: 只摘这一类脚注，**不**动 `所有者权益（或股东权益）合计` 这种
#: 括号内容本身就是指标名组成部分的情形。
_FOOTNOTE_SUFFIX = re.compile(
    r"[（(](?:净亏损|净收益|亏损|收益)[^）)]*号填列[）)]\s*$"
)


def clean_label(text: str) -> str:
    """剥掉科目名里不携带财务语义的前缀。

    `一、营业总收入` → `营业总收入`；`加:营业外收入` → `营业外收入`；
    `净利润（净亏损以"-"号填列）` → `净利润`。

    前缀本身也不稳定（同一份报表里可能有也可能没有），
    留着会让「科目名精确匹配」通道无故失配。反复剥离直到不再变化，
    以应对叠加前缀的情况。
    """
    if not text:
        return ""
    out = text.strip()
    # 先摘脚注后缀（一次性，不做循环）
    out = _FOOTNOTE_SUFFIX.sub("", out).strip()
    changed = True
    while changed:
        changed = False
        for pattern in (_SECTION_PREFIX, _QUALIFIER_PREFIX):
            new = pattern.sub("", out)
            if new != out:
                out, changed = new.strip(), True
    return out
